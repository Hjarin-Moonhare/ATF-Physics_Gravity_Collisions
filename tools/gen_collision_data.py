"""Writes src/collision_data.h from the measured sizes (sizes.json, from A-Body's p3_collision.py)
and the skeleton (the hand tip in the wrist's frame, used when the finger bone isn't found).
Rest distances: the closest in the bind pose or natural standing poses (tools/natural_rest.py)."""
import json
import os
import sys

import numpy as np

AUDIT_TOOLS = os.environ.get("ABODY_TOOLS", "abody_tools")
sys.path.insert(0, AUDIT_TOOLS)
import v06  # noqa: E402
import p3_physics as ph  # noqa: E402
import p3_collision as pc  # noqa: E402

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import natural_rest  # noqa: E402

sizes, natural = natural_rest.rest_distances()   # the bind pose AND natural standing poses
sizes["rest_distance_m"] = natural
skel = v06.load_skeleton(ph.SKEL_FACE)
W = v06.rest_world(skel)
tip = {s: W[f"{s}_Wrist"][:3, :3].T @ (W[f"{s}_Middle1"][:3, 3] - W[f"{s}_Wrist"][:3, 3]) for s in "LR"}      # wrist frame
fore = {s: W[f"{s}_Forearm"][:3, :3].T @ (W[f"{s}_Wrist"][:3, 3] - W[f"{s}_Forearm"][:3, 3]) for s in "LR"}   # forearm frame
vec = lambda v: "{" + ", ".join(f"{x:.4f}f" for x in v) + "}"  # noqa: E731

COLLIDERS = list(pc.SEGMENTS)                                       # upperarm, forearm, hand, thigh
SOFT = natural_rest.SOFT                                            # p3_collision's groups + the glutes
GROUPS = list(SOFT)                                                 # breast, belly, innerthigh, glute
MAXPUSH = natural_rest.MAX_PUSH
lines = ["// Generated by tools/gen_collision_data.py from A-Body's measurements; do not edit by hand.",
         "#pragma once", "", f"constexpr int kNumColliders = {len(COLLIDERS)};",
         "// collider kinds: " + ", ".join(f"{i} {c}" for i, c in enumerate(COLLIDERS)),
         "constexpr const char* kColliderBoneA[kNumColliders] = {" + ", ".join(f'"{pc.SEGMENTS[c][0]}"' for c in COLLIDERS) + "};",
         "constexpr const char* kColliderBoneB[kNumColliders] = {" + ", ".join(f'"{pc.SEGMENTS[c][1]}"' for c in COLLIDERS) + "};",
         "constexpr float kColliderRadius[kNumColliders] = {" + ", ".join(f"{sizes['collider_radius_m'][c]:.4f}f" for c in COLLIDERS) + "};",
         "// each capsule starts this far down its limb (0 = at the joint; tools/natural_rest.py TRIM)",
         "constexpr float kColliderStart[kNumColliders] = {" + ", ".join(f"{natural_rest.TRIM.get(c, 0.0):.2f}f" for c in COLLIDERS) + "};",
         f"constexpr float kHandTipInWrist[2][3] = {{{vec(tip['L'])}, {vec(tip['R'])}}};   // when the finger bone isn't found",
         f"constexpr float kWristInForearm[2][3] = {{{vec(fore['L'])}, {vec(fore['R'])}}};   // when the wrist isn't found",
         "", f"constexpr int kNumGroups = {len(GROUPS)};",
         "// soft groups: " + ", ".join(f"{i} {g}" for i, g in enumerate(GROUPS)),
         "constexpr float kGroupMaxPush[kNumGroups] = {" + ", ".join(f"{MAXPUSH[g]:.3f}f" for g in GROUPS) + "};",
         "// which colliders a group meets: 0 none, 1 both sides, 2 own side only, 3 other side only",
         "constexpr int kGroupMeets[kNumGroups][kNumColliders] = {"]
for g in GROUPS:
    rule = SOFT[g][1]
    lines.append("    {" + ", ".join(str({"B": 1, "S": 2, "O": 3}.get(rule.get(c), 0)) for c in COLLIDERS) + "},")
lines.append("};")
soft = []
for g, (bones, _) in SOFT.items():
    for b in bones:
        soft += [(g, b.format(s=s), s) for s in "LR"] if "{s}" in b else [(g, b, None)]
lines += ["", "struct SoftBoneDef { const char* name; int group; int side; float radius;",
          "                      float restToCollider[kNumColliders][2]; int pairWith[4]; float restToPair[4]; };",
          "// side: 0 left, 1 right, -1 middle; restToCollider[kind][collider side]: distance in the rest pose (m), 0 = none;",
          "// pairWith: indices of the other side's bones of the same group (soft against soft), -1 = none",
          f"constexpr int kNumSoft = {len(soft)};", "constexpr SoftBoneDef kSoft[kNumSoft] = {"]
index = {n: i for i, (_, n, _) in enumerate(soft)}
for g, n, s in soft:
    rc = []
    for c in COLLIDERS:
        rc.append("{" + ", ".join(f"{sizes['rest_distance_m'].get(f'{n}|{c}|{cs}', 0.0):.6f}f" for cs in "LR") + "}")
    pairs = [(index[m], sizes["rest_distance_m"][f"{n}|{m}"]) for (g2, m, s2) in soft
             if f"{n}|{m}" in sizes["rest_distance_m"]][:4]
    pw = [p[0] for p in pairs] + [-1] * (4 - len(pairs))
    pr = [p[1] for p in pairs] + [0.0] * (4 - len(pairs))
    side = {"L": 0, "R": 1, None: -1}[s]
    lines.append(f'    {{"{n}", {GROUPS.index(g)}, {side}, {sizes["soft_radius_m"][n]:.4f}f, {{{", ".join(rc)}}}, '
                 f'{{{", ".join(map(str, pw))}}}, {{{", ".join(f"{x:.6f}f" for x in pr)}}}}},')
lines.append("};")
out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "collision_data.h")
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", out, len(soft), "soft bones; hand tip in wrist frame (cm)", {s: np.round(v * 100, 1).tolist() for s, v in tip.items()},
      "wrist in forearm", {s: np.round(v * 100, 1).tolist() for s, v in fore.items()})
