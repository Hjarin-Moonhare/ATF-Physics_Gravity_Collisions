"""Writes src/body_shape_data.h (body-shape physics): for each of the body's 50 TF_ spring bones, which part it
belongs to, the largest travel the release ships for it and the lowest damping, over all 15 installer settings
(5 physics presets x 3 extra-jiggle levels: the preset and jiggle tables in A-Body's build tree,
reports/phase3/physics/presets and jiggle, the ones the A-Body plugins were built from).

The plugin scales a body's jiggle by its shape and sliders; on each axis the scaled swing never travels further than
this ceiling, and the damping never drops below this floor, so no body moves more than a Max physics + Max jiggle
install already does (its stretch was simulated when the presets were made: p3_spring_presets.py, p3_spring_jiggle.py).
MaxDist is per COM axis (side, fore/aft, vertical), as the record stores it (60 fps travel = MaxDist / 60 m).
"""
import json
import os

AUDIT = os.environ.get("ABODY_AUDIT", "abody_audit")
PRESETS = ("Realistic", "Low", "Medium", "High", "Max")
JIGGLE = ("None", "Normal", "Max")
# part of each bone by name; every other TF_ bone (flanks, lower back, lats, pelvis, perineum) follows the body only
PARTS = ["breast", "butt", "belly", "thigh", "hip", "calf", "arm", "torso"]
PREFIX = [("TF_Breast_", "breast"), ("TF_Glute_", "butt"), ("TF_Abdomen_", "belly"), ("TF_Thigh_", "thigh"),
          ("TF_Hip_Outer_", "hip"), ("TF_Calf_", "calf"), ("TF_UpperArm_", "arm")]
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "body_shape_data.h")


def table(preset, level):
    if level == "None":
        path = os.path.join(AUDIT, r"reports\phase3\physics\presets", f"{preset}.json")
    else:
        path = os.path.join(AUDIT, r"reports\phase3\physics\jiggle", f"{preset}_{level}.json")
    return path, json.load(open(path))


def main():
    tables = {(p, j): table(p, j) for p in PRESETS for j in JIGGLE}
    bones = sorted(tables[("Realistic", "None")][1])
    most, least = {}, {}
    for (p, j), (path, t) in tables.items():
        assert sorted(t) == bones, path
        for b in bones:
            m, d = t[b]["travel_cm"], t[b]["damping"]   # "travel_cm" holds the record's MaxDist (see the docstring)
            most[b] = [max(a, c) for a, c in zip(most.get(b, m), m)]
            least[b] = [min(a, c) for a, c in zip(least.get(b, d), d)]
    top = tables[("Max", "Max")][1]
    same = all(most[b] == top[b]["travel_cm"] for b in bones)   # expected: Max + Max is the largest everywhere
    vec = lambda v: "{" + ", ".join(f"{x:.4f}f" for x in v) + "}"  # noqa: E731
    part_of = lambda b: next((p for pre, p in PREFIX if b.startswith(pre)), "torso")  # noqa: E731
    lines = ["// Generated by tools/gen_body_shape_data.py from A-Body's preset and jiggle tables; do not edit by hand.",
             "#pragma once", "",
             "// the parts a body's sliders scale (torso: flanks, lower back, lats, pelvis, perineum follow the body only)",
             "enum BodyPart { " + ", ".join(f"kPart{p.capitalize()}" for p in PARTS) + ", kNumParts };",
             "constexpr const char* kPartName[kNumParts] = {" + ", ".join(f'"{p}"' for p in PARTS) + "};", "",
             "// per bone: maxDist = the largest MaxDist the release ships (per COM axis: side, fore/aft, vertical; as the",
             f"// record stores it) and damp = the lowest damping ratio, over all {len(tables)} physics x extra-jiggle settings"
             + (" (= Max physics + Max jiggle)" if same else ""),
             "struct ShapeBoneDef { const char* name; int part; float maxDist[3]; float damp[3]; };",
             f"constexpr int kNumShapeBones = {len(bones)};", "constexpr ShapeBoneDef kShapeBones[kNumShapeBones] = {"]
    for b in bones:
        lines.append(f'    {{"{b}", kPart{part_of(b).capitalize()}, {vec(most[b])}, {vec(least[b])}}},')
    lines.append("};")
    open(OUT, "w", newline="\n").write("\n".join(lines) + "\n")
    counts = {p: sum(part_of(b) == p for b in bones) for p in PARTS}
    print(f"wrote {OUT}: {len(bones)} bones {counts}; Max + Max is the largest on every bone: {same}")


if __name__ == "__main__":
    main()
